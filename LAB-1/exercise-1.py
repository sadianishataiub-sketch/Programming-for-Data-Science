"""Write a program that inputs two numbers and displays their sum, difference, product, and
quotient. Convert the inputs to numeric values before calculating"""

x = int(input("enter 1st number: "))
y = int(input("enter 2nd number: "))

print(f"summation: {x + y}")
print(f"difference: {x - y}")
print(f"product: {x * y}")
print(f"quotient: {x // y}")
